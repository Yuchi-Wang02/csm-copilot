"""Small synthetic diagnostic suite, not independent or production validation."""

import hashlib
import json
from pathlib import Path

from csm_copilot.engine import Copilot, validate_draft

ROOT = Path(__file__).resolve().parents[1]


def evaluate():
    case_file = ROOT / "evaluation/cases.json"
    cases = json.loads(case_file.read_text(encoding="utf-8"))
    engine = Copilot()
    rows = []
    families = {s: {c["family"] for c in cases if c["split"] == s} for s in ("dev", "holdout")}
    assert not families["dev"] & families["holdout"]
    for c in cases:
        result = engine.triage_issue(c["text"])
        predicted = [x["category"] for x in result["candidates"]]
        rows.append({**c, "predicted": predicted, "correct": set(predicted) == set(c["expected"])})
    metrics = {}
    for split in ("dev", "holdout"):
        subset = [r for r in rows if r["split"] == split]
        correct = sum(r["correct"] for r in subset)
        metrics[split] = {
            "correct": correct,
            "total": len(subset),
            "exact_set_accuracy": round(correct / len(subset), 4),
            "families": len(families[split]),
        }
    expected_queue = {"acc_014", "acc_006", "acc_018"}
    queue = {a["account_id"] for a in engine.list_accounts()["accounts"]}
    queue_metric = {
        "expected": sorted(expected_queue),
        "actual": sorted(queue),
        "false_positives": len(queue - expected_queue),
        "false_negatives": len(expected_queue - queue),
    }
    # Counterexamples make the boundary of a promise-pattern lint explicit.
    promise_cases = [
        ("We guarantee approval tomorrow.", True),
        ("We guarantee launch on Friday.", True),
        ("We will fix this today.", True),
        ("保证明天审核通过。", True),
        ("Launch has already been approved.", True),
        ("You can confidently launch this Friday.", True),
        ("Please share the affected platform and logs.", False),
        ("I cannot guarantee launch on Friday.", False),
    ]
    promise_rows = [
        {"text": text, "expected_flag": gold, "actual_flag": bool(validate_draft(text)["flags"])}
        for text, gold in promise_cases
    ]
    report = {
        "dataset": "30 synthetic messages / 15 families; English and Chinese",
        "authorship": "Cases and implementation were AI-assisted in the same development session.",
        "holdout_boundary": "Family-disjoint diagnostic partition; not a blinded independent test.",
        "cases_sha256": hashlib.sha256(case_file.read_text(encoding="utf-8").encode()).hexdigest(),
        "model_inference": False,
        "method": "lexical retrieval baseline + deterministic workflow",
        "metrics": metrics,
        "queue_selection": queue_metric,
        "triage_cases": rows,
        "promise_lint": {
            "cases": promise_rows,
            "true_positives": sum(r["expected_flag"] and r["actual_flag"] for r in promise_rows),
            "false_negatives": sum(
                r["expected_flag"] and not r["actual_flag"] for r in promise_rows
            ),
            "false_positives": sum(
                not r["expected_flag"] and r["actual_flag"] for r in promise_rows
            ),
        },
        "not_measured": [
            "Customer outcomes",
            "CSM time savings",
            "Independent human agreement",
            "LLM orchestration quality",
            "General semantic claim support",
        ],
    }
    out = ROOT / "evidence/evaluation.json"
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = [
        "# Evaluation results",
        "",
        "Generated by `python evaluation/run.py`.",
        "",
        "> Synthetic, developer-authored diagnostics. No live model inference or independent human validation.",
        "",
        "| Partition | Exact category-set matches | Accuracy | Families |",
        "|---|---:|---:|---:|",
    ]
    for split, metric in metrics.items():
        lines.append(
            f"| {split} | {metric['correct']}/{metric['total']} | {metric['exact_set_accuracy']:.1%} | {metric['families']} |"
        )
    lines += [
        "",
        "Bilingual pairs stay in the same partition. The holdout name describes the split, not a blinded evaluation. "
        "Cases were created alongside the implementation, so these results cannot establish generalization.",
        "",
        "## Failure cases",
        "",
        "| Case | Expected | Retrieved |",
        "|---|---|---|",
    ]
    for row in rows:
        if not row["correct"]:
            lines.append(
                f"| {row['id']} | {', '.join(row['expected'])} | {', '.join(row['predicted'])} |"
            )
    lint = report["promise_lint"]
    lines += [
        "",
        "The baseline misses indirect wording and retrieves negated symptoms. Keep these visible; "
        "do not add the exact holdout phrases to inflate the score. A next iteration should use independently written cases and compare semantic retrieval on the same inputs.",
        "",
        "## Workflow and promise checks",
        "",
        f"- Fixed five-account queue: {queue_metric['false_positives']} false positives, {queue_metric['false_negatives']} false negatives.",
        f"- Eight promise-lint probes: {lint['true_positives']} true positives, {lint['false_negatives']} false negatives, {lint['false_positives']} false positives.",
        "- A negated promise can be flagged; confident unsupported statements can pass. This is why the tool always returns `semantic_verification: not_performed`.",
        "- Unit tests separately check platform separation, missing evidence, draft side effects, contact boundaries and partial-confirmation retesting.",
        "- The MCP smoke client exercises eight tools, prompt retrieval, invalid-ID handling and phrase-boundary probes over stdio. It is scripted, not model-driven.",
        "",
        "## A separate lexical repair",
        "",
        "The [phrase-boundary review](TRIAGE_BOUNDARIES.md) preserves actual pre-change outputs and compares them with current calls on 12 development probes. It removes four selected substring collisions while retaining two known semantic failures. The original 30-message inputs and the results above are unchanged. The new probes are not an independent holdout.",
        "",
        "## Reproduction",
        "",
        "```sh",
        "python -m pytest -q",
        "python evaluation/run.py",
        "python scripts/mcp_smoke.py --output evidence/mcp-transcript.json",
        "```",
        "",
        f"Cases SHA-256: `{report['cases_sha256']}`",
        "",
        "Raw per-case outputs: [evaluation.json](evaluation.json). No timing, revenue or productivity benefit has been measured.",
        "",
    ]
    (ROOT / "evidence/EVALUATION.md").write_text("\n".join(lines), encoding="utf-8")
    print(
        json.dumps(
            {"metrics": metrics, "promise_lint": {k: v for k, v in lint.items() if k != "cases"}}
        )
    )
    return report


if __name__ == "__main__":
    evaluate()
